export const MESSAGES: Record<Lang, Dict> = {
  es: { ...es, ...LAUNCH_ES },
  en: { ...en, ...LAUNCH_EN },
  nl: { ...nl, ...LAUNCH_NL },
};

export type I18n = { k: string; p?: Record<string, string | number> };

/** Format a key in a language, falling back to English, then to the key itself. */
export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const s = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] === undefined ? `{${k}}` : String(params[k])));
}

/** English rendering of an i18n message — the canonical text stored in run records. */
export const en_ = (k: string, p: Record<string, string | number> = {}): string => t('en', k, p);
